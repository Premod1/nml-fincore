<?php

namespace Nml\FinCore\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\MorphMany;

class RecurringJournalEntry extends Model
{
    protected $fillable = [
        'name',
        'code',
        'description',
        'frequency',
        'interval',
        'start_date',
        'end_date',
        'next_run_date',
        'last_run_at',
        'max_iterations',
        'iteration_count',
        'status',
        'is_active',
        'auto_post',
        'currency',
        'exchange_rate',
        'sbu_code',
        'lines_template',
        'metadata',
        'created_by',
    ];

    protected $casts = [
        'start_date'      => 'date',
        'end_date'        => 'date',
        'next_run_date'   => 'date',
        'last_run_at'     => 'datetime',
        'lines_template'  => 'array',
        'metadata'        => 'array',
        'is_active'       => 'boolean',
        'auto_post'       => 'boolean',
        'interval'        => 'integer',
        'max_iterations'  => 'integer',
        'iteration_count' => 'integer',
        'exchange_rate'   => 'float',
    ];

    public function getTable()
    {
        return config('accounting.table_prefix', 'fincore_') . 'recurring_journal_entries';
    }

    /**
     * Get all journal entries generated by this recurring template.
     */
    public function journalEntries(): MorphMany
    {
        return $this->morphMany(JournalEntry::class, 'journalable');
    }

    /**
     * Scope for recurring templates that are due to be processed on or before a given date.
     */
    public function scopeDue(Builder $query, ?string $asOfDate = null): Builder
    {
        $date = $asOfDate ?: now()->format('Y-m-d');

        return $query->where('is_active', true)
            ->where('status', 'active')
            ->whereDate('start_date', '<=', $date)
            ->whereDate('next_run_date', '<=', $date);
    }

    /**
     * Check if the template is due as of a specific date.
     */
    public function isDue(?string $asOfDate = null): bool
    {
        $date = $asOfDate ?: now()->format('Y-m-d');

        if (!$this->is_active || $this->status !== 'active') {
            return false;
        }

        if ($this->start_date && $this->start_date->format('Y-m-d') > $date) {
            return false;
        }

        if ($this->isExpired($date) || $this->hasReachedMaxIterations()) {
            return false;
        }

        return $this->next_run_date && $this->next_run_date->format('Y-m-d') <= $date;
    }

    /**
     * Check if the recurring template has passed its expiration end_date.
     */
    public function isExpired(?string $asOfDate = null): bool
    {
        if (!$this->end_date) {
            return false;
        }

        $date = $asOfDate ?: now()->format('Y-m-d');
        return $this->end_date->format('Y-m-d') < $date;
    }

    /**
     * Check if the iteration limit has been reached.
     */
    public function hasReachedMaxIterations(): bool
    {
        if ($this->max_iterations === null) {
            return false;
        }

        return $this->iteration_count >= $this->max_iterations;
    }

    /**
     * Pause the recurring entry.
     */
    public function pause(): void
    {
        $this->update(['status' => 'paused']);
    }

    /**
     * Resume a paused recurring entry.
     */
    public function resume(): void
    {
        $this->update(['status' => 'active', 'is_active' => true]);
    }

    /**
     * Cancel the recurring entry.
     */
    public function cancel(): void
    {
        $this->update(['status' => 'cancelled', 'is_active' => false]);
    }
}
